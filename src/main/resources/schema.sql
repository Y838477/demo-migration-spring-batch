-- H2 Database Schema for Authors and Books
-- This is optional as Hibernate will auto-create tables based on entities

CREATE TABLE IF NOT EXISTS AUTHORS (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(255) NOT NULL UNIQUE,
    NATIONALITY VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS BOOKS (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    TITLE VARCHAR(500) NOT NULL,
    PUBLICATION_YEAR INTEGER,
    OPEN_LIBRARY_ID VARCHAR(100),
    AUTHOR_ID BIGINT NOT NULL,
    FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHORS(ID)
);

-- Indexes for better query performance
CREATE INDEX IF NOT EXISTS IDX_BOOKS_AUTHOR_ID ON BOOKS(AUTHOR_ID);
CREATE INDEX IF NOT EXISTS IDX_BOOKS_TITLE ON BOOKS(TITLE);
CREATE INDEX IF NOT EXISTS IDX_AUTHORS_NATIONALITY ON AUTHORS(NATIONALITY);
